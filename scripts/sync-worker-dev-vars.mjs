/**
 * Syncs worker/.dev.vars from the repo root .env for local `wrangler dev`.
 *
 * `task dev` runs the multi-issuer OAuth Worker on http://localhost:8787.
 * wrangler only loads secrets from worker/.dev.vars (not the root .env), so
 * this script keeps Google / Dropbox client ids + secrets in sync without
 * committing them.
 *
 * Usage: node scripts/sync-worker-dev-vars.mjs
 * Exit 0 even when .env is missing (prints a short skip message).
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const envPath = path.join(rootDir, ".env");
const outPath = path.join(rootDir, "worker", ".dev.vars");

const KEYS = [
  "GOOGLE_CLIENT_ID",
  "GOOGLE_CLIENT_SECRET",
  "DROPBOX_CLIENT_ID",
  "DROPBOX_CLIENT_SECRET",
  "CHROME_EXTENSION_ID",
  "WORKER_ALLOWED_EXTENSION_ORIGINS",
];

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  const out = {};
  for (const line of fs.readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function main() {
  if (!fs.existsSync(envPath)) {
    console.warn("[sync-worker-dev-vars] No root .env found — worker/.dev.vars left unchanged.");
    return;
  }

  const env = loadEnvFile(envPath);
  const extensionId = env.CHROME_EXTENSION_ID || "";
  const allowed =
    env.WORKER_ALLOWED_EXTENSION_ORIGINS ||
    (extensionId ? `chrome-extension://${extensionId}` : "");

  const lines = [
    "# Generated by scripts/sync-worker-dev-vars.mjs from root .env",
    "# Used by `task worker:dev` / `task dev` (wrangler). Do not commit.",
    "",
    `GOOGLE_CLIENT_ID=${env.GOOGLE_CLIENT_ID || ""}`,
    `GOOGLE_CLIENT_SECRET=${env.GOOGLE_CLIENT_SECRET || ""}`,
    `DROPBOX_CLIENT_ID=${env.DROPBOX_CLIENT_ID || ""}`,
    `DROPBOX_CLIENT_SECRET=${env.DROPBOX_CLIENT_SECRET || ""}`,
    `ALLOWED_EXTENSION_ORIGINS=${allowed}`,
    "",
  ];

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, lines.join("\n"), { mode: 0o600 });

  const configured = KEYS.filter((k) => {
    if (k === "CHROME_EXTENSION_ID" || k === "WORKER_ALLOWED_EXTENSION_ORIGINS") {
      return Boolean(allowed);
    }
    return Boolean(env[k]);
  });
  console.log(
    `[sync-worker-dev-vars] Wrote ${path.relative(rootDir, outPath)} ` +
      `(${configured.length} keys populated from .env).`,
  );
}

main();
