/**
 * Syncs worker/.dev.vars from the repo root .env for local `wrangler dev`.
 *
 * `task dev` runs the multi-issuer Worker on http://localhost:63972 (OAuth +
 * optional POST /feedback). wrangler only loads secrets from worker/.dev.vars
 * (not the root .env), so this script keeps Google / Dropbox / feedback vars
 * in sync without committing them.
 *
 * Usage: node scripts/sync-worker-dev-vars.mjs
 * Exit 0 even when .env is missing (prints a short skip message).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getChromeExtensionId } from "./chrome-extension-id.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const envPath = path.join(rootDir, ".env");
const outPath = path.join(rootDir, "worker", ".dev.vars");

/** Keys counted in the "populated" log summary when non-empty after sync. */
const KEYS = [
  "GOOGLE_CLIENT_ID",
  "GOOGLE_WEB_CLIENT_ID",
  "GOOGLE_CLIENT_SECRET",
  "DROPBOX_CLIENT_ID",
  "DROPBOX_CLIENT_SECRET",
  "CHROME_EXTENSION_ID",
  "WORKER_ALLOWED_EXTENSION_ORIGINS",
  "GITHUB_FEEDBACK_TOKEN",
  "GITHUB_REPO_OWNER",
  "GITHUB_REPO_NAME",
  "GITHUB_FEEDBACK_LABELS",
];

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  const out = {};
  for (const line of fs.readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

/**
 * Firefox and Safari regenerate their extension UUIDs per profile/install, so
 * neither origin can be pinned like CHROME_EXTENSION_ID. Keep both scheme
 * wildcards in the derived dev allow-list so local OAuth works on all targets.
 */
const FIREFOX_ORIGIN_WILDCARD = "moz-extension://*";
const SAFARI_ORIGIN_WILDCARD = "safari-web-extension://*";

function main() {
  if (!fs.existsSync(envPath)) {
    console.warn("[sync-worker-dev-vars] No root .env found — worker/.dev.vars left unchanged.");
    return;
  }

  const env = loadEnvFile(envPath);
  const extensionId = env.CHROME_EXTENSION_ID || "";
  // esbuild.config.mjs builds dev/watch extension bundles with this key instead
  // of CHROME_EXTENSION_PUBLIC_KEY, so the local Worker's allow-list must admit
  // that derived id too or `task dev` OAuth calls 403 with forbidden_origin.
  const devPublicKey = env.CHROME_EXTENSION_PUBLIC_KEY_DEV || "";
  const devExtensionId = devPublicKey ? getChromeExtensionId(devPublicKey) : "";

  // Prefer explicit WORKER_ALLOWED_EXTENSION_ORIGINS, else derive Chrome id(s).
  const base = env.WORKER_ALLOWED_EXTENSION_ORIGINS
    ? env.WORKER_ALLOWED_EXTENSION_ORIGINS
    : [extensionId, devExtensionId]
        .filter(Boolean)
        .map((id) => `chrome-extension://${id}`)
        .join(",");

  // This file only feeds the *local* `task worker:dev` Worker, so always admit
  // the dev origin plus dynamic Firefox/Safari origins even when
  // WORKER_ALLOWED_EXTENSION_ORIGINS is set explicitly. That variable is
  // production-oriented and may omit dev targets; doing so only breaks local
  // OAuth with forbidden_origin and never widens the deployed Worker.
  const required = [
    devExtensionId ? `chrome-extension://${devExtensionId}` : "",
    FIREFOX_ORIGIN_WILDCARD,
    SAFARI_ORIGIN_WILDCARD,
  ].filter(Boolean);
  const parts = base
    ? base
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean)
    : [];
  for (const origin of required) {
    if (!parts.includes(origin)) {
      parts.push(origin);
    }
  }
  const allowed = parts.join(",");

  const lines = [
    "# Generated by scripts/sync-worker-dev-vars.mjs from root .env",
    "# Used by `task worker:dev` / `task dev` (wrangler). Do not commit.",
    "",
    `GOOGLE_CLIENT_ID=${env.GOOGLE_CLIENT_ID || ""}`,
    `GOOGLE_WEB_CLIENT_ID=${env.GOOGLE_WEB_CLIENT_ID || ""}`,
    `GOOGLE_CLIENT_SECRET=${env.GOOGLE_CLIENT_SECRET || ""}`,
    `DROPBOX_CLIENT_ID=${env.DROPBOX_CLIENT_ID || ""}`,
    `DROPBOX_CLIENT_SECRET=${env.DROPBOX_CLIENT_SECRET || ""}`,
    `ALLOWED_EXTENSION_ORIGINS=${allowed}`,
    "",
    "# Opt-in product feedback → GitHub Issues (POST /feedback)",
    `GITHUB_FEEDBACK_TOKEN=${env.GITHUB_FEEDBACK_TOKEN || ""}`,
    `GITHUB_REPO_OWNER=${env.GITHUB_REPO_OWNER || "gnasdev"}`,
    `GITHUB_REPO_NAME=${env.GITHUB_REPO_NAME || "gn-tracing"}`,
    `GITHUB_FEEDBACK_LABELS=${env.GITHUB_FEEDBACK_LABELS || "feedback"}`,
    "",
  ];

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, lines.join("\n"), { mode: 0o600 });

  const configured = KEYS.filter((k) => {
    if (k === "CHROME_EXTENSION_ID" || k === "WORKER_ALLOWED_EXTENSION_ORIGINS") {
      return Boolean(allowed);
    }
    if (k === "GITHUB_REPO_OWNER" || k === "GITHUB_REPO_NAME" || k === "GITHUB_FEEDBACK_LABELS") {
      // Always written with defaults; count only when user set them or feedback token is present.
      return Boolean(env[k] || env.GITHUB_FEEDBACK_TOKEN);
    }
    return Boolean(env[k]);
  });
  console.log(
    `[sync-worker-dev-vars] Wrote ${path.relative(rootDir, outPath)} ` +
      `(${configured.length} keys populated from .env).`,
  );
}

main();
