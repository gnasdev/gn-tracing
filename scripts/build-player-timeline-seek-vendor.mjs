/**
 * Bundle src/shared/player-timeline-seek.ts as a browser IIFE for player/player.js.
 * Single runtime source of truth (same pure helpers unit tests import).
 *
 * Usage: node scripts/build-player-timeline-seek-vendor.mjs
 * Or: npm run vendor:player-timeline-seek
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "src/shared/player-timeline-seek.ts");
const outDir = path.join(root, "player/vendor/player-timeline-seek");
const outFile = path.join(outDir, "player-timeline-seek.iife.js");

if (!fs.existsSync(entry)) {
  console.error("Missing src/shared/player-timeline-seek.ts");
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });

await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  globalName: "GnPlayerTimelineSeek",
  platform: "browser",
  target: "chrome120",
  outfile: outFile,
  logLevel: "info",
});

// Attach stable alias used by player.js
const bundled = fs.readFileSync(outFile, "utf8");
const footer = `
(function (global) {
  "use strict";
  var api = global.GnPlayerTimelineSeek;
  if (!api || typeof api.reconcileSeekClock !== "function") {
    console.error("[GN Tracing] player-timeline-seek vendor missing exports");
    return;
  }
  global.gnPlayerTimelineSeek = api;
})(typeof globalThis !== "undefined" ? globalThis : window);
`;
fs.writeFileSync(
  outFile,
  `/* Generated by scripts/build-player-timeline-seek-vendor.mjs — do not edit by hand.
 * Source: src/shared/player-timeline-seek.ts. Rebuild: npm run vendor:player-timeline-seek
 */
${bundled}
${footer}`,
);

console.log("Wrote", path.relative(root, outFile));
