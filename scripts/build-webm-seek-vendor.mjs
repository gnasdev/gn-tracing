/**
 * Rebuild the browser IIFE for player seek-fix from the same npm package
 * used by src/shared/webm-seek-fix.ts, then wrap it with the shared API
 * surface (window.gnMakeWebmSeekable).
 *
 * Usage: node scripts/build-webm-seek-vendor.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "player/vendor/webm-seek-fix");
const libEntry = path.join(root, "node_modules/webm-duration-fix/lib/index.js");
const bundledLib = path.join(outDir, "webm-duration-fix.bundle.js");
const outFile = path.join(outDir, "webm-seek-fix.iife.js");

if (!fs.existsSync(libEntry)) {
  console.error("Missing webm-duration-fix. Run: npm install");
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });

await esbuild.build({
  entryPoints: [libEntry],
  bundle: true,
  format: "iife",
  globalName: "GnWebmDurationFixLib",
  platform: "browser",
  outfile: bundledLib,
  logLevel: "info",
});

const libCode = fs.readFileSync(bundledLib, "utf8");
const wrapper = `/* Generated by scripts/build-webm-seek-vendor.mjs — do not edit by hand.
 * Primary: webm-duration-fix (ISC). Rebuild: npm run vendor:webm-seek
 */
${libCode}
(function (global) {
  "use strict";
  var lib = global.GnWebmDurationFixLib;
  var fixWithCues = lib && (lib.default || lib);
  if (typeof fixWithCues !== "function") {
    console.error("[GN Tracing] webm-duration-fix bundle missing default export");
    return;
  }

  function isWebmMime(mimeType) {
    if (!mimeType) return true;
    var normalized = String(mimeType).toLowerCase();
    return normalized.indexOf("webm") !== -1 || normalized.indexOf("matroska") !== -1;
  }

  /**
   * Force a playable WebM mime. Never leave application/octet-stream (common
   * from cloud download Content-Type) on the blob URL — Chromium random-seek
   * is unreliable for MediaRecorder WebM when the blob type is not video/*.
   */
  function withMimeType(blob, mimeType) {
    if (!mimeType) return blob;
    var current = String(blob.type || "").toLowerCase();
    var wanted = String(mimeType).toLowerCase();
    if (current && isWebmMime(current) && current === wanted) return blob;
    if (current && isWebmMime(current) && isWebmMime(wanted)) {
      if (current.indexOf("codecs") !== -1 || wanted.indexOf("codecs") === -1) return blob;
    }
    return new Blob([blob], { type: mimeType });
  }

  /**
   * Same contract as src/shared/webm-seek-fix.ts makeWebmSeekable.
   * @param {Blob} input
   * @param {{ mimeType?: string }} [options]
   * @returns {Promise<{ ok: true, blob: Blob, method: "cues" | "noop" } | { ok: false, blob: Blob, reason: string }>}
   */
  async function gnMakeWebmSeekable(input, options) {
    options = options || {};
    var mimeType = options.mimeType || (input && input.type) || "video/webm";
    if (!(input instanceof Blob) || input.size === 0) {
      return { ok: false, blob: input, reason: "empty-blob" };
    }
    if (!isWebmMime(mimeType)) {
      return { ok: true, blob: input, method: "noop" };
    }
    try {
      var fixed = await fixWithCues(input);
      if (!(fixed instanceof Blob) || fixed.size === 0) {
        return { ok: false, blob: withMimeType(input, mimeType), reason: "cues-rewrite-empty" };
      }
      return { ok: true, blob: withMimeType(fixed, mimeType), method: "cues" };
    } catch (error) {
      var reason = error instanceof Error ? error.message : "webm-cues-fix-failed";
      return { ok: false, blob: withMimeType(input, mimeType), reason: reason };
    }
  }

  global.gnMakeWebmSeekable = gnMakeWebmSeekable;
})(typeof globalThis !== "undefined" ? globalThis : window);
`;

fs.writeFileSync(outFile, wrapper);
fs.unlinkSync(bundledLib);

